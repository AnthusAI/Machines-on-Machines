"""Generate the site's published stylesheets from their sources, each as one dual file (see tools/scale_css.py).

Papyrus publishes only `web/css/site-theme.css` and everything under `web/assets/`. Every published stylesheet here is
generated, so never edit one by hand:

- `web/assets/mom-tokens.css` from `design/system/tokens.css` (itself generated by `python3 tools/build_tokens_css.py`)
- `web/assets/mom-components.css` from `design/system/components/bundle.css`
- `web/css/site-theme.css` from `web/css-src/site-theme.src.css` (edit this one; it is not published)

On phones (viewport under 600px) the file applies the designed sizes; from 600px up it applies the same rules at 75%
(SCALE in tools/scale_css.py).

    python3 tools/sync_design_assets.py           write the generated stylesheets
    python3 tools/sync_design_assets.py --check   exit 1 when one differs from its source (CI)
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from scale_css import dual_stylesheet  # noqa: E402

REPOSITORY_ROOT = Path(__file__).resolve().parent.parent
SITE_STYLESHEET_SOURCE = "site-theme.src.css"  # the one stylesheet that also scales the root font size, so rem in other stylesheets scales too
COPIES = (
    (REPOSITORY_ROOT / "design" / "system" / "tokens.css", REPOSITORY_ROOT / "web" / "assets" / "mom-tokens.css"),
    (REPOSITORY_ROOT / "design" / "system" / "components" / "bundle.css", REPOSITORY_ROOT / "web" / "assets" / "mom-components.css"),
    (REPOSITORY_ROOT / "web" / "css-src" / "site-theme.src.css", REPOSITORY_ROOT / "web" / "css" / "site-theme.css"),
)


def generated_text(source: Path) -> str:
    return dual_stylesheet(source.read_text(encoding="utf-8"), str(source.relative_to(REPOSITORY_ROOT)), scale_root=source.name == SITE_STYLESHEET_SOURCE)


def stale_copies() -> list[Path]:
    return [target for source, target in COPIES if not target.is_file() or target.read_text(encoding="utf-8") != generated_text(source)]


if __name__ == "__main__":
    if "--check" in sys.argv[1:]:
        stale = stale_copies()
        for target in stale:
            print(f"{target.relative_to(REPOSITORY_ROOT)} is out of date; run python3 tools/sync_design_assets.py")
        raise SystemExit(1 if stale else 0)
    for source, target in COPIES:
        target.write_text(generated_text(source), encoding="utf-8")
        print(f"wrote {target.relative_to(REPOSITORY_ROOT)}")
