"""Turn design/system/tokens.json into CSS custom properties for the site and for previews."""

import json
import pathlib
import sys

repository_root = pathlib.Path(__file__).resolve().parent.parent
tokens_path = repository_root / "design" / "system" / "tokens.json"
output_path = repository_root / "design" / "system" / "tokens.css"


def declarations_for_theme(color_tokens, theme_id):
    return [f"  --{token['name']}: {token['value'][theme_id]};" for token in color_tokens]


def declarations_for_flat_family(family):
    return [f"  --{token['name']}: {token['value']};" for token in family.get("tokens", [])]


def build_css(tokens):
    color_tokens = tokens["color"]["tokens"]
    fixed_declarations = [
        f"  --font-display: {tokens['type']['families']['display']};",
        f"  --font-text: {tokens['type']['families']['text']};",
    ]
    for family_name in ("spacing", "radius", "angle", "size", "figure"):
        fixed_declarations += declarations_for_flat_family(tokens[family_name])
    light_declarations = "\n".join(declarations_for_theme(color_tokens, "light"))
    dark_declarations = "\n".join(declarations_for_theme(color_tokens, "dark"))
    return "\n".join([
        "/* Generated by tools/build_tokens_css.py from tokens.json. Do not edit by hand. */",
        ":root {",
        "\n".join(fixed_declarations),
        light_declarations,
        "  color-scheme: light dark;",
        "}",
        "@media (prefers-color-scheme: dark) {",
        "  :root:not([data-theme=\"light\"]) {",
        dark_declarations.replace("  --", "    --"),
        "  }",
        "}",
        ":root[data-theme=\"dark\"] {",
        dark_declarations,
        "}",
        "",
    ])


if __name__ == "__main__":
    generated_css = build_css(json.loads(tokens_path.read_text()))
    if "--check" in sys.argv:
        if output_path.read_text() != generated_css:
            sys.exit("tokens.css is out of date; run python3 tools/build_tokens_css.py")
    else:
        output_path.write_text(generated_css)
