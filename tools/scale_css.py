"""Make a stylesheet dual: the original sizes on phones, every size scaled on wider screens.

Everything on the site renders at SCALE of its designed size on viewports PHONE_MAX + 1 pixels wide and up; phones keep the
designed sizes. To try another scale (80% or 85%), change SCALE here, run `python3 tools/sync_design_assets.py`, and commit.

A source stylesheet becomes one file (the site stylesheet also sets the root font size, see below):

    @media (max-width: 599px) { ...the source rules, verbatim... }
    @media (min-width: 600px) { ...the same rules with every px and rem number multiplied by SCALE... }

Scaling multiplies `px` numbers, and `rem` numbers in media-query breakpoints, as a browser zoom would. It leaves
unitless numbers, hex colors, comments, strings and everything inside url() alone.

Lengths in `rem` inside rules are not rewritten; the scaled block instead sets the page's root font size to SCALE of the
browser's, which scales every `rem` on the page, including those in stylesheets this repository does not own (the core
`papyrus-home-page.css` and Papyrus's inline styles are written in `rem`). The site's own sources use no `rem`; if one
ever does, it scales through the root in the same way. `@charset`, `@import` and `@font-face`
stay at the top level, once. The output depends only on the source text, so running it again changes nothing.
"""

from __future__ import annotations

import math
import re

SCALE = 0.75
PHONE_MAX = 599

# Minimum text sizes in RENDERED pixels, after the scale. They are the only place the policy's numbers live; see "Minimum text size"
# in design/system/README.md. The scale shrinks every size, so a size written in the sources is raised to its floor in both versions.
READING_FLOOR_PX = 18    # article, wiki and post body, and other long paragraphs
INTERFACE_FLOOR_PX = 14  # dek, blurb, meta lines, chips, nav, captions, form labels, buttons: everything that is not reading text
LABEL_FLOOR_PX = 13      # uppercase and letter-spaced micro-labels; the smallest text anywhere
INTERFACE_SELECTORS = (".mom-nav-pill",)  # uppercase, but navigation: it gets the interface floor, not the label floor
READING_SELECTORS = (".mom-article-body", ".mom-article-body h3", ".mom-home-purpose", ".home-page-explainer-body")
LINE_HEIGHT_AT_LEAST = {"reading": 1.6, "interface": 1.35, "label": 1.3}  # times the font size, for a line height written in px
FLOOR_PX = {"reading": READING_FLOOR_PX, "interface": INTERFACE_FLOOR_PX, "label": LABEL_FLOOR_PX}
RHYTHM_PX = 4  # the vertical rhythm unit in the sources (--rhythm); a line height raised by a floor stays a whole number of units

HEADER = "/* Generated by tools/sync_design_assets.py from {source}. Do not edit by hand. */\n"
UNTOUCHED = re.compile(r"/\*.*?\*/|url\([^)]*\)|\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*'", re.S)
NUMBER_BEFORE = r"(?<![\w#.-])(-?\d*\.?\d+)"
PIXELS = re.compile(NUMBER_BEFORE + r"px\b")
ROOT_EMS = re.compile(NUMBER_BEFORE + r"rem\b")
MEDIA_PRELUDE = re.compile(r"@media[^{;]*")
TOP_LEVEL_UNSCALED = ("@charset", "@import", "@font-face")


def scaled_number(found: re.Match, unit: str) -> str:
    text = f"{float(found.group(1)) * SCALE:.3f}".rstrip("0").rstrip(".")
    return f"{'0' if text in ('', '-0') else text}{unit}"


def scale_unprotected(text: str) -> str:
    text = PIXELS.sub(lambda found: scaled_number(found, "px"), text)
    return MEDIA_PRELUDE.sub(lambda prelude: ROOT_EMS.sub(lambda found: scaled_number(found, "rem"), prelude.group(0)), text)


def scale_lengths(css: str) -> str:
    pieces, position = [], 0
    for protected in UNTOUCHED.finditer(css):
        pieces.append(scale_unprotected(css[position:protected.start()]))
        pieces.append(protected.group(0))
        position = protected.end()
    pieces.append(scale_unprotected(css[position:]))
    return "".join(pieces)


LEAF_RULE = re.compile(r"([^{}]+)\{([^{}]*)\}")
PLAIN_PIXEL_SIZE = re.compile(r"^\s*(\d*\.?\d+)px\s*$")
FONT_SHORTHAND = re.compile(r"^((?:\s*(?:italic|oblique|normal|bold|\d{3}))*)\s*(\d*\.?\d+)px(?:\s*/\s*(\d*\.?\d+px|[\d.]+))?\s+(.+)$", re.S)
PIXEL_VALUE = re.compile(r"^\s*(\d*\.?\d+)px\s*$")


def text_role(selector: str, body: str) -> str:
    parts = [" ".join(re.sub(r"\x00\d+\x00", " ", part).split()) for part in selector.split(",")]
    if any(part in READING_SELECTORS for part in parts):
        return "reading"
    if any(part in INTERFACE_SELECTORS for part in parts):
        return "interface"
    if re.search(r"text-transform:\s*uppercase|letter-spacing:\s*[^;]*\d", body):
        return "label"
    return "interface"


def compact_number(value: float) -> str:
    return f"{value:.3f}".rstrip("0").rstrip(".")


def raised_line_height(declared_px: float, size_px: float, role: str, rhythm: float) -> float:
    wanted = math.ceil(size_px * LINE_HEIGHT_AT_LEAST[role] / rhythm - 1e-9) * rhythm
    return max(declared_px, wanted)


def floor_rule_body(selector: str, body: str, rhythm: float) -> str:
    """Raise every plain px font size in one rule to its role's floor, and a px line height that the larger text would crowd."""
    if "font" not in body or selector.lstrip().startswith("@"):
        return body
    role = text_role(selector, body)
    floor = FLOOR_PX[role]
    declarations = body.split(";")
    floored = False
    for index, declaration in enumerate(declarations):
        if ":" not in declaration:
            continue
        prop, _, value = declaration.partition(":")
        name = prop.strip()
        if name == "font-size":
            found = PLAIN_PIXEL_SIZE.match(value)
            if found and float(found.group(1)) < floor:
                declarations[index] = f"{prop}: {compact_number(floor)}px"
                floored = True
        elif name == "font":
            found = FONT_SHORTHAND.match(value.strip())
            if found and float(found.group(2)) < floor:
                line = found.group(3)
                if line and line.endswith("px"):
                    line = f"{compact_number(raised_line_height(float(line[:-2]), floor, role, rhythm))}px"
                line_text = f"/{line}" if line else ""
                weight = found.group(1).strip()
                declarations[index] = f"{prop}: {weight + ' ' if weight else ''}{compact_number(floor)}px{line_text} {found.group(4)}"
                floored = True
    if floored:
        for index, declaration in enumerate(declarations):
            prop, _, value = declaration.partition(":")
            found = PIXEL_VALUE.match(value) if prop.strip() == "line-height" else None
            if found:
                size = floor
                declarations[index] = f"{prop}: {compact_number(raised_line_height(float(found.group(1)), size, role, rhythm))}px"
    return ";".join(declarations)


def floor_font_sizes(css: str, rhythm: float) -> str:
    hidden = []

    def hide(found: re.Match) -> str:
        hidden.append(found.group(0))
        return f"\x00{len(hidden) - 1}\x00"

    floored = LEAF_RULE.sub(lambda rule: f"{rule.group(1)}{{{floor_rule_body(rule.group(1), rule.group(2), rhythm)}}}", UNTOUCHED.sub(hide, css))
    return re.sub(r"\x00(\d+)\x00", lambda found: hidden[int(found.group(1))], floored)


def top_level_statements(css: str) -> list[str]:
    """Split into top-level statements (a rule with its block, or an at-rule ending in a semicolon), keeping every character."""
    statements, start, depth, position = [], 0, 0, 0
    while position < len(css):
        protected = UNTOUCHED.match(css, position)
        if protected:
            position = protected.end()
            continue
        character = css[position]
        if character == "{":
            depth += 1
        elif character == "}":
            depth -= 1
            if depth == 0:
                statements.append(css[start:position + 1])
                start = position + 1
        elif character == ";" and depth == 0:
            statements.append(css[start:position + 1])
            start = position + 1
        position += 1
    if css[start:].strip():
        statements.append(css[start:])
    return statements


def dual_stylesheet(css: str, source_name: str, scale_root: bool = False) -> str:
    hoisted, body = [], []
    for statement in top_level_statements(css):
        (hoisted if statement.lstrip().startswith(TOP_LEVEL_UNSCALED) else body).append(statement)
    original = "".join(body).strip("\n")
    phone_version = floor_font_sizes(original, RHYTHM_PX)
    scaled_version = floor_font_sizes(scale_lengths(original), RHYTHM_PX * SCALE)
    root_rule = f"html {{ font-size: {SCALE * 100:g}%; }}\n" if scale_root else ""
    return (
        HEADER.format(source=source_name)
        + "".join(statement.strip("\n") + "\n" for statement in hoisted)
        + f"@media (max-width: {PHONE_MAX}px) {{\n{phone_version}\n}}\n"
        + f"@media (min-width: {PHONE_MAX + 1}px) {{\n{root_rule}{scaled_version}\n}}\n"
    )
