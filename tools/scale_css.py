"""Make a stylesheet dual: the original sizes on phones, every size scaled on wider screens.

Everything on the site renders at SCALE of its designed size on viewports PHONE_MAX + 1 pixels wide and up; phones keep the
designed sizes. To try another scale (80% or 85%), change SCALE here, run `python3 tools/sync_design_assets.py`, and commit.

A source stylesheet becomes one file (the site stylesheet also sets the root font size, see below):

    @media (max-width: 599px) { ...the source rules, verbatim... }
    @media (min-width: 600px) { ...the same rules with every px and rem number multiplied by SCALE... }

Scaling multiplies `px` numbers, and `rem` numbers in media-query breakpoints, as a browser zoom would. It leaves
unitless numbers, hex colors, comments, strings and everything inside url() alone.

Lengths in `rem` inside rules are not rewritten; the scaled block instead sets the page's root font size to SCALE of the
browser's, which scales every `rem` on the page, including those in stylesheets this repository does not own (the core
`papyrus-home-page.css` and Papyrus's inline styles are written in `rem`). The site's own sources use no `rem`; if one
ever does, it scales through the root in the same way. `@charset`, `@import` and `@font-face`
stay at the top level, once. The output depends only on the source text, so running it again changes nothing.
"""

from __future__ import annotations

import re

SCALE = 0.75
PHONE_MAX = 599

HEADER = "/* Generated by tools/sync_design_assets.py from {source}. Do not edit by hand. */\n"
UNTOUCHED = re.compile(r"/\*.*?\*/|url\([^)]*\)|\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*'", re.S)
NUMBER_BEFORE = r"(?<![\w#.-])(-?\d*\.?\d+)"
PIXELS = re.compile(NUMBER_BEFORE + r"px\b")
ROOT_EMS = re.compile(NUMBER_BEFORE + r"rem\b")
MEDIA_PRELUDE = re.compile(r"@media[^{;]*")
TOP_LEVEL_UNSCALED = ("@charset", "@import", "@font-face")


def scaled_number(found: re.Match, unit: str) -> str:
    text = f"{float(found.group(1)) * SCALE:.3f}".rstrip("0").rstrip(".")
    return f"{'0' if text in ('', '-0') else text}{unit}"


def scale_unprotected(text: str) -> str:
    text = PIXELS.sub(lambda found: scaled_number(found, "px"), text)
    return MEDIA_PRELUDE.sub(lambda prelude: ROOT_EMS.sub(lambda found: scaled_number(found, "rem"), prelude.group(0)), text)


def scale_lengths(css: str) -> str:
    pieces, position = [], 0
    for protected in UNTOUCHED.finditer(css):
        pieces.append(scale_unprotected(css[position:protected.start()]))
        pieces.append(protected.group(0))
        position = protected.end()
    pieces.append(scale_unprotected(css[position:]))
    return "".join(pieces)


def top_level_statements(css: str) -> list[str]:
    """Split into top-level statements (a rule with its block, or an at-rule ending in a semicolon), keeping every character."""
    statements, start, depth, position = [], 0, 0, 0
    while position < len(css):
        protected = UNTOUCHED.match(css, position)
        if protected:
            position = protected.end()
            continue
        character = css[position]
        if character == "{":
            depth += 1
        elif character == "}":
            depth -= 1
            if depth == 0:
                statements.append(css[start:position + 1])
                start = position + 1
        elif character == ";" and depth == 0:
            statements.append(css[start:position + 1])
            start = position + 1
        position += 1
    if css[start:].strip():
        statements.append(css[start:])
    return statements


def dual_stylesheet(css: str, source_name: str, scale_root: bool = False) -> str:
    hoisted, body = [], []
    for statement in top_level_statements(css):
        (hoisted if statement.lstrip().startswith(TOP_LEVEL_UNSCALED) else body).append(statement)
    original = "".join(body).strip("\n")
    root_rule = f"html {{ font-size: {SCALE * 100:g}%; }}\n" if scale_root else ""
    return (
        HEADER.format(source=source_name)
        + "".join(statement.strip("\n") + "\n" for statement in hoisted)
        + f"@media (max-width: {PHONE_MAX}px) {{\n{original}\n}}\n"
        + f"@media (min-width: {PHONE_MAX + 1}px) {{\n{root_rule}{scale_lengths(original)}\n}}\n"
    )
